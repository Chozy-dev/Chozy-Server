CREATE TABLE chozy.members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id varchar(100) NOT NULL,
    password_hash varchar(255) NOT NULL,
    nickname varchar(100) NOT NULL,
    email varchar(320) NOT NULL,
    terms_agreed_at timestamptz NOT NULL,
    privacy_agreed_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Reserved for trusted verification only. Algorithm/encoding contract is pending.
    verified_di_hash varchar(128),
    di_verified_at timestamptz,
    CONSTRAINT uq_members_login_id UNIQUE (login_id),
    CONSTRAINT uq_members_email UNIQUE (email),
    CONSTRAINT uq_members_verified_di_hash UNIQUE (verified_di_hash),
    CONSTRAINT ck_members_login_id CHECK (login_id ~ '^[a-z0-9][a-z0-9_.-]{0,99}$'),
    CONSTRAINT ck_members_email CHECK (
        email = lower(email COLLATE "C") AND email !~ '[[:space:]]'
        AND email ~ '^[^@]+@[^@]+$'
    ),
    CONSTRAINT ck_members_password_hash CHECK (length(btrim(password_hash)) > 0),
    CONSTRAINT ck_members_nickname CHECK (nickname = btrim(nickname) AND length(nickname) > 0),
    CONSTRAINT ck_members_verified_di CHECK (
        (verified_di_hash IS NULL AND di_verified_at IS NULL)
        OR (verified_di_hash IS NOT NULL AND di_verified_at IS NOT NULL
            AND verified_di_hash ~ '^[A-Za-z0-9_-]{32,128}$')
    )
);
COMMENT ON COLUMN chozy.members.verified_di_hash IS
    'Trusted verification output only; never phone number, raw DI or self-asserted input. Contract pending.';
