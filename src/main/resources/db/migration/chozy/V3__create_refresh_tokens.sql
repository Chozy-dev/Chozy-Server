CREATE TABLE chozy.refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES chozy.members(id),
    token_hash varchar(64) NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at timestamptz,
    CONSTRAINT ck_refresh_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_refresh_tokens_member ON chozy.refresh_tokens(member_id);
CREATE INDEX ix_refresh_tokens_expiry ON chozy.refresh_tokens(expires_at);
